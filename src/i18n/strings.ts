export function ui(lang: Lang, key: string, vars?: Record<string, string>): string {
  const raw = TABLE[lang]?.[key] ?? EN[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? `{${k}}`);
}
